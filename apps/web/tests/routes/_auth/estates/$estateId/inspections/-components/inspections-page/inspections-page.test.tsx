import { fireEvent } from "@testing-library/react";
import {
  renderWithProviders,
  screen,
  waitFor,
  within,
} from "@tests/test-utils";
import type { ReactNode } from "react";
import { toast } from "sonner";
import { beforeEach, expect, it, vi } from "vitest";
import { InspectionsPage } from "@/routes/_auth/estates/$estateId/inspections/-components/inspections-page/inspections-page";

const L1 = /L-1/u;
const L2 = /L-2/u;
const P1 = /P-1/u;
const LAST_GENERATED = /Last generated by Casey Doe/u;

const blockA = { id: "a", name: "Block A" };
const blockB = { id: "b", name: "Block B" };
const level1 = { id: "a1", name: "Level 1" };

function check(overrides: Record<string, unknown>) {
  return {
    id: "check",
    assetId: "asset",
    assetReference: "L-1",
    assetName: "Lobby light",
    categoryLabel: "Lighting",
    block: blockA,
    level: null,
    dueOn: "2026-11-01",
    dueBasis: "NEVER_INSPECTED",
    interval: null,
    intervalSource: null,
    status: "DUE",
    result: null,
    ...overrides,
  };
}

const overdue = check({
  id: "c1",
  assetId: "a-1",
  assetReference: "L-1",
  status: "OVERDUE",
  dueOn: "2026-10-01",
  dueBasis: "INTERVAL",
  interval: { value: 6, unit: "MONTH" },
  intervalSource: "ASSET",
});
const due = check({
  id: "c2",
  assetId: "a-2",
  assetReference: "L-2",
  assetName: "Stair light",
  level: level1,
  dueBasis: "INTERVAL",
  interval: { value: 1, unit: "YEAR" },
  intervalSource: "CATEGORY",
});
const done = check({
  id: "c3",
  assetId: "a-3",
  assetReference: "P-1",
  assetName: "Booster pump",
  categoryLabel: "Pump",
  block: blockB,
  dueBasis: "PREDICTION",
  status: "DONE",
  result: { id: "r-1", outcome: "PASS", inspectedOn: "2026-11-03" },
});

const state = vi.hoisted(() => ({
  data: undefined as unknown,
  error: null as Error | null,
  refetch: vi.fn(),
  generate: vi.fn(),
  canCreate: true,
}));

beforeEach(() => {
  state.data = {
    month: "2026-11-01",
    estateActive: true,
    generatedAt: null,
    generatedByName: null,
    overdueCount: 1,
    dueCount: 1,
    doneCount: 1,
    checks: [overdue, due, done],
    flaggedCategoryCount: 1,
    unscheduled: [
      {
        assetId: "a-9",
        assetReference: "F-1",
        assetName: "Exit sign",
        categoryLabel: "Lighting",
      },
    ],
  };
  state.error = null;
  state.refetch = vi.fn();
  state.generate = vi.fn(() => Promise.resolve({ added: 2 }));
  state.canCreate = true;
  vi.mocked(toast.success).mockReset();
});

vi.mock("sonner", () => ({ toast: { success: vi.fn() } }));
vi.mock("@/lib/inspection-list", () => ({
  useInspectionList: () => ({
    data: state.data,
    error: state.error,
    isPending: !(state.data || state.error),
    refetch: state.refetch,
  }),
  useGenerateInspectionList: () => ({
    mutateAsync: state.generate,
    isPending: false,
  }),
}));
vi.mock("@/lib/inspections", () => ({
  useInspectionAccess: () => ({ canCreate: state.canCreate }),
}));
vi.mock("@tanstack/react-router", () => ({
  Link: ({
    children,
    to,
    params,
  }: {
    children: ReactNode;
    to: string;
    params?: Record<string, string>;
  }) => (
    <a
      href={Object.entries(params ?? {}).reduce(
        (path, [key, value]) => path.replace(`$${key}`, value),
        to
      )}
    >
      {children}
    </a>
  ),
}));

function card(name: string) {
  return within(screen.getByRole("region", { name }));
}

function group(name: string) {
  return within(screen.getByRole("region", { name }));
}

function cells(region: string, reference: string) {
  return within(
    group(region).getByRole("row", { name: new RegExp(reference, "u") })
  )
    .getAllByRole("cell")
    .map((cell) => cell.textContent);
}

it("names the month and summarises the checks in cards", () => {
  renderWithProviders(<InspectionsPage estateId="oak" />);
  screen.getByRole("heading", { name: "Inspections", level: 1 });
  screen.getByText("November 2026");
  card("Overdue").getByText("1");
  card("Overdue").getByText("Missed in an earlier month");
  card("Due this month").getByText("1");
  card("Done this month").getByText("1");
  card("Not scheduled").getByText("1");
  expect(
    card("Not scheduled")
      .getByRole("link", { name: "Set check schedules" })
      .getAttribute("href")
  ).toBe("/estates/oak/inspections/schedules");
  const views = within(
    screen.getByRole("navigation", { name: "Inspection views" })
  );
  expect(
    views
      .getAllByRole("link")
      .map((link) => [link.textContent, link.getAttribute("href")])
  ).toEqual([
    ["Due checks", "/estates/oak/inspections"],
    ["Check schedules", "/estates/oak/inspections/schedules"],
  ]);
});

it("hides the Not scheduled card when every asset is scheduled", () => {
  state.data = { ...(state.data as object), unscheduled: [] };
  renderWithProviders(<InspectionsPage estateId="oak" />);
  expect(screen.queryByRole("region", { name: "Not scheduled" })).toBeNull();
});

it("groups checks by block, then level", () => {
  renderWithProviders(<InspectionsPage estateId="oak" />);
  const blocks = screen
    .getAllByRole("heading", { level: 2 })
    .map((heading) => heading.textContent);
  expect(blocks).toEqual(expect.arrayContaining(["Block A", "Block B"]));
  group("Block A, Block-wide").getByRole("row", { name: L1 });
  group("Block A, Level 1").getByRole("row", { name: L2 });
  group("Block B, Block-wide").getByRole("row", { name: P1 });
});

it("shows each check's due date, basis, status and action", () => {
  renderWithProviders(<InspectionsPage estateId="oak" />);
  expect(cells("Block A, Block-wide", "L-1")).toEqual([
    "L-1 · Lobby light",
    "Lighting",
    "1 Oct 2026",
    "Every 6 months (asset)",
    "Overdue",
    "Record inspection",
  ]);
  expect(cells("Block A, Level 1", "L-2").slice(3)).toEqual([
    "Every 1 year (category)",
    "Due",
    "Record inspection",
  ]);
  expect(cells("Block B, Block-wide", "P-1").slice(3)).toEqual([
    "Expected",
    "Done · Pass",
    "View result",
  ]);
  expect(
    group("Block A, Block-wide")
      .getByRole("link", { name: "Record inspection" })
      .getAttribute("href")
  ).toBe("/estates/oak/assets/a-1/inspections/new");
  expect(
    group("Block B, Block-wide")
      .getByRole("link", { name: "View result" })
      .getAttribute("href")
  ).toBe("/estates/oak/assets/a-3/inspections/r-1");
});

it("says Never inspected for a first check", () => {
  state.data = {
    ...(state.data as object),
    checks: [check({ assetReference: "N-1" })],
  };
  renderWithProviders(<InspectionsPage estateId="oak" />);
  expect(cells("Block A, Block-wide", "N-1")[3]).toBe("Never inspected");
});

it("leaves out Record inspection without permission", () => {
  state.canCreate = false;
  renderWithProviders(<InspectionsPage estateId="oak" />);
  expect(screen.queryByRole("link", { name: "Record inspection" })).toBeNull();
  screen.getByRole("link", { name: "View result" });
});

it("lists unscheduled assets with a way to set an interval", () => {
  renderWithProviders(<InspectionsPage estateId="oak" />);
  const section = within(
    screen.getByRole("region", { name: "Not scheduled assets" })
  );
  section.getByText("F-1 · Exit sign");
  section.getByText("Lighting");
});

it("generates the list and says how many checks were added", async () => {
  renderWithProviders(<InspectionsPage estateId="oak" />);
  screen.getByText("This month's list hasn't been generated yet.");
  fireEvent.click(screen.getByRole("button", { name: "Generate list" }));
  await waitFor(() => expect(state.generate).toHaveBeenCalled());
  await waitFor(() =>
    expect(toast.success).toHaveBeenCalledWith("Added 2 checks.")
  );
});

it("says when regenerating found nothing new", async () => {
  state.data = {
    ...(state.data as object),
    generatedAt: "2026-11-02T01:00:00Z",
    generatedByName: "Casey Doe",
  };
  state.generate = vi.fn(() => Promise.resolve({ added: 0 }));
  renderWithProviders(<InspectionsPage estateId="oak" />);
  expect(screen.getByText(LAST_GENERATED)).toBeTruthy();
  screen.getByText(
    "This adds checks that are now due and never adds the same check twice."
  );
  fireEvent.click(screen.getByRole("button", { name: "Regenerate list" }));
  await waitFor(() =>
    expect(toast.success).toHaveBeenCalledWith("No new checks are due.")
  );
});

it("shows a failed generation", async () => {
  state.generate = vi.fn(() =>
    Promise.reject(new Error("This estate is inactive."))
  );
  renderWithProviders(<InspectionsPage estateId="oak" />);
  fireEvent.click(screen.getByRole("button", { name: "Generate list" }));
  expect((await screen.findByRole("alert")).textContent).toContain(
    "This estate is inactive."
  );
});

it("cannot generate in an inactive estate", () => {
  state.data = { ...(state.data as object), estateActive: false };
  renderWithProviders(<InspectionsPage estateId="oak" />);
  expect(
    screen
      .getByRole("button", { name: "Generate list" })
      .hasAttribute("disabled")
  ).toBe(true);
});

it("says when there are no checks this month", () => {
  state.data = { ...(state.data as object), checks: [] };
  renderWithProviders(<InspectionsPage estateId="oak" />);
  const empty = screen
    .getAllByRole("status")
    .find((element) => element.textContent?.includes("No checks this month"));
  expect(empty).toBeDefined();
});

it("shows a load error", () => {
  state.data = undefined;
  state.error = new Error("Estate not found.");
  renderWithProviders(<InspectionsPage estateId="oak" />);
  expect(screen.getByRole("alert").textContent).toContain("Estate not found.");
  fireEvent.click(screen.getByRole("button", { name: "Retry" }));
  expect(state.refetch).toHaveBeenCalled();
});

it("explains that nothing can be due when no category is flagged", () => {
  state.data = {
    ...(state.data as object),
    checks: [],
    flaggedCategoryCount: 0,
  };
  renderWithProviders(<InspectionsPage estateId="oak" />);
  const note = within(screen.getByRole("note", { name: "No regular checks" }));
  note.getByText(
    "No equipment has regular checks turned on yet, so nothing is due."
  );
  expect(
    note
      .getByRole("link", { name: "Turn on regular checks" })
      .getAttribute("href")
  ).toBe("/estates/oak/inspections/schedules");
});

it("keeps the note alongside checks still open from before", () => {
  state.data = { ...(state.data as object), flaggedCategoryCount: 0 };
  renderWithProviders(<InspectionsPage estateId="oak" />);
  screen.getByRole("note", { name: "No regular checks" });
  screen.getByRole("row", { name: L1 });
});

it("has no note while a category is flagged", () => {
  renderWithProviders(<InspectionsPage estateId="oak" />);
  expect(screen.queryByRole("note", { name: "No regular checks" })).toBeNull();
});
