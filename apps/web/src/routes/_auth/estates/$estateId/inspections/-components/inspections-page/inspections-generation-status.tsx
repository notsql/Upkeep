import { Alert, AlertDescription } from "@proj/ui/components/alert";
import type { InspectionList } from "@/lib/inspection-list";

export function InspectionsGenerationStatus({
  data,
  error,
}: {
  data: InspectionList;
  error: string | undefined;
}) {
  return (
    <div className="grid gap-2">
      {data.generatedAt ? (
        <p className="text-muted-foreground text-sm">
          Last generated by {data.generatedByName ?? "Unknown user"} ·{" "}
          {new Date(data.generatedAt).toLocaleString()}
        </p>
      ) : null}
      <p className="text-muted-foreground text-sm">
        {data.generatedAt
          ? "Regenerating adds newly due checks and never duplicates them."
          : "This month's list hasn't been generated yet."}
      </p>
      {data.estateActive ? null : (
        <p className="text-muted-foreground text-sm" role="note">
          This estate is inactive, so its inspection list cannot be generated.
        </p>
      )}
      {error ? (
        <Alert variant="destructive">
          <AlertDescription>{error}</AlertDescription>
        </Alert>
      ) : null}
    </div>
  );
}
